// CSS is generated; React Native and Tailwind read the same source directly.
const fs = require('node:fs');
const path = require('node:path');
const tokens = require('../src/constants/design-tokens.json');
function hsl(hex) {
  const [r, g, b] = hex.slice(1).match(/../g).map(value => parseInt(value, 16) / 255);
  const max = Math.max(r, g, b), min = Math.min(r, g, b), delta = max - min;
  const lightness = (max + min) / 2;
  const saturation = delta === 0 ? 0 : delta / (1 - Math.abs(2 * lightness - 1));
  const hue = delta === 0 ? 0 : max === r ? ((g - b) / delta + 6) % 6 : max === g ? (b - r) / delta + 2 : (r - g) / delta + 4;
  return [(hue * 60).toFixed(3), (saturation * 100).toFixed(3) + '%', (lightness * 100).toFixed(3) + '%'].join(' ');
}
function declarations(palette, indent) {
  return Object.entries(tokens.roles).map(([role, key]) => indent + '--' + role + ': ' + hsl(palette[key]) + ';').join('\n');
}
const css = [
  '/* Generated by npm run theme:sync from src/constants/design-tokens.json. */',
  '@tailwind base;', '@tailwind components;', '@tailwind utilities;',
  ':root {',
  '  --font-display: ' + tokens.fonts.web.sans + ';',
  '  --font-mono: ' + tokens.fonts.web.mono + ';',
  '  --font-rounded: ' + tokens.fonts.web.rounded + ';',
  '  --font-serif: ' + tokens.fonts.web.serif + ';',
  '}', '@layer base {', '  :root {', declarations(tokens.light, '    '),
  ...Object.entries(tokens.radii).map(([key, value]) => '    --radius-' + key + ': ' + value + 'px;'),
  '    --radius: ' + tokens.radii.md + 'px;',
  '  }', '  .dark:root {', declarations(tokens.dark, '    '), '  }', '}', ''
].join('\n');
const destination = path.resolve(__dirname, '../src/global.css');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(destination, 'utf8').replace(/\r\n/g, '\n') !== css) {
    console.error('Design token CSS is stale. Run npm run theme:sync.');
    process.exitCode = 1;
  } else console.log('Design token CSS is synchronized.');
} else {
  fs.writeFileSync(destination, css);
  console.log('Updated src/global.css from design tokens.');
}
